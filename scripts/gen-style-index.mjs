// Generates src/renderer/styles/index.generated.ts from the files in
// src/renderer/styles/definitions/, so adding a style is "add one file".
import { readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dir = join(root, 'src/renderer/styles/definitions');
const out = join(root, 'src/renderer/styles/index.generated.ts');

const files = readdirSync(dir)
  .filter((f) => f.endsWith('.ts') && !f.endsWith('.d.ts') && !f.endsWith('.test.ts'))
  .sort();

const ident = (f) => 's_' + f.replace(/\.ts$/, '').replace(/[^A-Za-z0-9]/g, '_');
const lines = [
  '// GENERATED by scripts/gen-style-index.mjs - do not edit.',
  "import type { StyleDefinition } from './schema';",
  ...files.map((f) => `import ${ident(f)} from './definitions/${f.replace(/\.ts$/, '')}';`),
  '',
  `export const STYLE_DEFINITIONS: StyleDefinition[] = [${files.map(ident).join(', ')}];`,
  '',
];
const text = lines.join('\n');
if (!existsSync(out) || readFileSync(out, 'utf8') !== text) writeFileSync(out, text);
